-- Tabla de pedidos (si ya existe, sólo suma la columna nueva)
create table if not exists public.pedidos (
  numero    integer generated by default as identity (start with 1) primary key,
  creado_en timestamptz not null default now(),
  codigo    text,
  cliente   text,
  telefono  text,
  total     integer,
  metodo    text,
  cuotas    integer,
  entrega   text,
  datos     jsonb
);
alter table public.pedidos add column if not exists origen_hash text;
create index if not exists pedidos_origen_idx on public.pedidos (origen_hash, creado_en desc);

-- Nadie entra a la tabla desde la web: ni leer, ni cargar, ni borrar (sólo vos desde el panel de Supabase).
alter table public.pedidos enable row level security;
alter table public.pedidos force row level security;
revoke all on table public.pedidos from anon, authenticated;
revoke all on sequence public.pedidos_numero_seq from anon, authenticated;

-- La única puerta: guarda el pedido (con controles) y devuelve su número.
create or replace function public.registrar_pedido(p jsonb)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  n integer;
  ip text;
  origen text;
  total_num integer;
  recientes integer;
begin
  -- 1) que el pedido tenga sentido
  if p is null or jsonb_typeof(p) <> 'object' then raise exception 'pedido inválido'; end if;
  if pg_column_size(p) > 16000 then raise exception 'pedido demasiado grande'; end if;
  if length(coalesce(p->>'cliente', '')) not between 3 and 120 then raise exception 'falta el nombre'; end if;
  if length(regexp_replace(coalesce(p->>'telefono', ''), '\D', '', 'g')) not between 6 and 15 then raise exception 'teléfono inválido'; end if;
  if coalesce(jsonb_typeof(p->'items'), '') <> 'array' or jsonb_array_length(p->'items') not between 1 and 20 then raise exception 'pedido sin productos'; end if;
  if coalesce(p->>'total', '') !~ '^\d{1,9}$' then raise exception 'total inválido'; end if;
  total_num := (p->>'total')::integer;
  if total_num < 1000 or total_num > 20000000 then raise exception 'total inválido'; end if;
  if coalesce(p->>'metodo', '') not in ('mercadopago', 'transferencia', 'whatsapp') then raise exception 'medio de pago inválido'; end if;
  if coalesce(p->>'entrega', '') not in ('envio', 'retiro') then raise exception 'entrega inválida'; end if;

  -- 2) freno a quien quiera llenar la tabla: máx. 6 pedidos cada 10 minutos desde una misma conexión,
  --    y 120 por hora en total. Se guarda sólo un hash de la IP, no la IP.
  ip := split_part(coalesce(current_setting('request.headers', true)::json->>'x-forwarded-for', ''), ',', 1);
  origen := md5('bz-' || ip);
  select count(*) into recientes from public.pedidos where origen_hash = origen and creado_en > now() - interval '10 minutes';
  if recientes >= 6 then raise exception 'demasiados pedidos seguidos, probá en unos minutos'; end if;
  select count(*) into recientes from public.pedidos where creado_en > now() - interval '1 hour';
  if recientes >= 120 then raise exception 'demasiados pedidos, probá en un rato'; end if;

  insert into public.pedidos (codigo, cliente, telefono, total, metodo, cuotas, entrega, datos, origen_hash)
  values (left(p->>'codigo', 40), left(p->>'cliente', 120), left(p->>'telefono', 30), total_num,
          p->>'metodo', least(greatest(coalesce((p->>'cuotas')::int, 1), 1), 12), p->>'entrega', p, origen)
  returning numero into n;
  return n;
end;
$$;

revoke all on function public.registrar_pedido(jsonb) from public;
grant execute on function public.registrar_pedido(jsonb) to anon, authenticated;

notify pgrst, 'reload schema';
